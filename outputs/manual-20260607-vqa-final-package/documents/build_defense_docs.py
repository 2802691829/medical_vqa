def set_east_asian_font(run, font_name="微软雅黑"):
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)


def set_cell_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_style_font(style, font_name="微软雅黑", size=11, color=None, bold=False):
    style.font.name = font_name
    style._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)
    style.font.size = Pt(size)
    style.font.bold = bold
    if color:
        style.font.color.rgb = RGBColor.from_string(color)


def setup_doc(title, subtitle):
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin = Cm(2.0)
    section.right_margin = Cm(2.0)

    set_style_font(doc.styles["Normal"], size=11)
    set_style_font(doc.styles["Heading 1"], size=16, color="1E5AA8", bold=True)
    set_style_font(doc.styles["Heading 2"], size=13, color="0B9EA4", bold=True)
    set_style_font(doc.styles["Heading 3"], size=12, color="102033", bold=True)

    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(title)
    set_east_asian_font(title_run)
    title_run.font.size = Pt(20)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(30, 90, 168)

    sub_p = doc.add_paragraph()
    sub_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = sub_p.add_run(subtitle)
    set_east_asian_font(sub_run)
    sub_run.font.size = Pt(11)
    sub_run.font.color.rgb = RGBColor(69, 90, 112)

    doc.add_paragraph()
    return doc


def add_meta_table(doc, rows):
    table = doc.add_table(rows=0, cols=2)
    table.style = "Table Grid"
    for k, v in rows:
        row = table.add_row()
        row.cells[0].text = k
        row.cells[1].text = v
        set_cell_shading(row.cells[0], "E6F0FA")
        for cell in row.cells:
            for p in cell.paragraphs:
                for r in p.runs:
                    set_east_asian_font(r)
                    r.font.size = Pt(10.5)
    doc.add_paragraph()


def add_para(doc, text, style=None, bold_label=False):
    p = doc.add_paragraph(style=style)
    if bold_label and "：" in text:
        label, rest = text.split("：", 1)
        r1 = p.add_run(label + "：")
        set_east_asian_font(r1)
        r1.font.bold = True
        r2 = p.add_run(rest)
        set_east_asian_font(r2)
    else:
        r = p.add_run(text)
        set_east_asian_font(r)
    p.paragraph_format.line_spacing = 1.18
    p.paragraph_format.space_after = Pt(6)
    return p


def add_slide_script(doc, no, title, seconds, script, transition="", emphasis=None):
    doc.add_heading(f"第 {no} 页：{title}", level=2)
    add_para(doc, f"建议用时：{seconds}", bold_label=True)
    add_para(doc, "演讲稿：", bold_label=True)
    for para in script:
        add_para(doc, para)
    if transition:
        add_para(doc, f"过渡句：{transition}", bold_label=True)
    if emphasis:
        add_para(doc, f"强调点：{emphasis}", bold_label=True)


